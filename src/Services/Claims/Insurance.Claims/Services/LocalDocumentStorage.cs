namespace Insurance.Claims.Services;

// Keeps files in a folder (ClaimDocuments:RootPath). In docker compose that folder is a named volume, so files
// survive the container being recreated. A relative path is resolved against the service's content root.
public class LocalDocumentStorage : IDocumentStorage
{
    private readonly string _root;

    public LocalDocumentStorage(IConfiguration config, IHostEnvironment environment)
    {
        var configured = config["ClaimDocuments:RootPath"]
            ?? throw new InvalidOperationException("ClaimDocuments:RootPath is missing.");
        _root = Path.GetFullPath(configured, environment.ContentRootPath);
        Directory.CreateDirectory(_root);
    }

    public async Task SaveAsync(string key, Stream content, CancellationToken ct = default)
    {
        var path = PathOf(key);
        try
        {
            await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write);
            await content.CopyToAsync(file, ct);
        }
        catch
        {
            File.Delete(path);      // don't leave half a file behind
            throw;
        }
    }

    public Task<Stream?> OpenReadAsync(string key, CancellationToken ct = default)
    {
        var path = PathOf(key);
        if (!File.Exists(path)) return Task.FromResult<Stream?>(null);

        Stream stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true);
        return Task.FromResult<Stream?>(stream);
    }

    public Task DeleteAsync(string key, CancellationToken ct = default)
    {
        File.Delete(PathOf(key));   // does nothing if the file isn't there
        return Task.CompletedTask;
    }

    // Keys are generated by ClaimDocumentService. This is a second line of defense against leaving the folder.
    private string PathOf(string key)
    {
        if (key != Path.GetFileName(key))
            throw new ArgumentException("A storage key can't contain a path.", nameof(key));
        return Path.Combine(_root, key);
    }
}
