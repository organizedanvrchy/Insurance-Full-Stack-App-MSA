/* Claims service: supporting documents for a claim, and the NeedsMoreInfo review step.
   Numbered 003 so it can't collide with another branch's 002 script. DatabaseMigrator runs each script once.
   The files themselves live in document storage (IDocumentStorage); this table holds only their details.
   Error numbers:
     50020 the claim already has the maximum number of documents
     50021 sending a claim back to the reviewer when it isn't waiting on the customer */

ALTER TABLE claims.Claims DROP CONSTRAINT CK_Claims_Status;
GO

ALTER TABLE claims.Claims ADD CONSTRAINT CK_Claims_Status
    CHECK (Status IN ('Submitted','UnderReview','NeedsMoreInfo','Approved','Rejected','Paid'));
GO

-- ClaimId is this service's own table, so it gets a real foreign key. UploadedByUserId belongs to Identity: plain id.
CREATE TABLE claims.ClaimDocuments (
    ClaimDocumentId  INT IDENTITY(1,1) CONSTRAINT PK_ClaimDocuments PRIMARY KEY,
    ClaimId          INT NOT NULL CONSTRAINT FK_ClaimDocuments_Claims REFERENCES claims.Claims(ClaimId),
    FileName         NVARCHAR(255) NOT NULL,          -- the customer's name for it, display only
    ContentType      NVARCHAR(100) NOT NULL,          -- detected from the file's contents
    SizeBytes        INT NOT NULL,
    StorageKey       NVARCHAR(100) NOT NULL,          -- generated by the service, never from the upload
    UploadedByUserId INT NOT NULL,
    UploadedAt       DATETIME2 NOT NULL CONSTRAINT DF_ClaimDocuments_UploadedAt DEFAULT SYSUTCDATETIME(),
    CONSTRAINT UQ_ClaimDocuments_StorageKey UNIQUE (StorageKey),
    CONSTRAINT CK_ClaimDocuments_Size CHECK (SizeBytes > 0)
);
CREATE INDEX IX_ClaimDocuments_ClaimId ON claims.ClaimDocuments(ClaimId);
GO

/* Add a document. The Claims service has already checked the owner, the claim's status and the file.
   This proc owns the rule that needs a lock: the per-claim limit, so two uploads at once can't both pass it. */
CREATE OR ALTER PROCEDURE claims.usp_ClaimDocument_Add
    @ClaimId          INT,
    @FileName         NVARCHAR(255),
    @ContentType      NVARCHAR(100),
    @SizeBytes        INT,
    @StorageKey       NVARCHAR(100),
    @UploadedByUserId INT,
    @MaxDocuments     INT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @Count INT, @Id INT, @Msg NVARCHAR(200);

    BEGIN TRANSACTION;

        SELECT @Count = COUNT(*)
        FROM claims.ClaimDocuments WITH (UPDLOCK, HOLDLOCK)
        WHERE ClaimId = @ClaimId;

        IF @Count >= @MaxDocuments
        BEGIN
            SET @Msg = CONCAT('A claim can have up to ', @MaxDocuments, ' documents.');
            THROW 50020, @Msg, 1;
        END

        INSERT INTO claims.ClaimDocuments (ClaimId, FileName, ContentType, SizeBytes, StorageKey, UploadedByUserId)
        VALUES (@ClaimId, @FileName, @ContentType, @SizeBytes, @StorageKey, @UploadedByUserId);

        SET @Id = SCOPE_IDENTITY();

    COMMIT TRANSACTION;

    SELECT * FROM claims.ClaimDocuments WHERE ClaimDocumentId = @Id;
END
GO

CREATE OR ALTER PROCEDURE claims.usp_ClaimDocument_GetByClaim
    @ClaimId INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT * FROM claims.ClaimDocuments
    WHERE ClaimId = @ClaimId
    ORDER BY UploadedAt, ClaimDocumentId;
END
GO

-- Matches on both ids, so a document can only be reached through the claim it belongs to.
CREATE OR ALTER PROCEDURE claims.usp_ClaimDocument_GetById
    @ClaimId         INT,
    @ClaimDocumentId INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT * FROM claims.ClaimDocuments
    WHERE ClaimId = @ClaimId AND ClaimDocumentId = @ClaimDocumentId;
END
GO

/* The customer has responded to a request for more information. ReviewedAt and ReviewedByUserId are left alone:
   they record the last admin who acted on the claim. */
CREATE OR ALTER PROCEDURE claims.usp_Claim_SendToReviewer
    @ClaimId INT,
    @UserId  INT
AS
BEGIN
    SET NOCOUNT ON;

    UPDATE claims.Claims
    SET Status = 'UnderReview'
    WHERE ClaimId = @ClaimId AND UserId = @UserId AND Status = 'NeedsMoreInfo';

    IF @@ROWCOUNT = 0
        THROW 50021, 'This claim isn''t waiting for more information. Please refresh and try again.', 1;

    SELECT * FROM claims.vw_ClaimDetails WHERE ClaimId = @ClaimId;
END
GO

/* A claim waiting on the customer is still open. */
CREATE OR ALTER PROCEDURE claims.usp_Claim_CountByUser
    @UserIds NVARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT UserId,
           COUNT(*) AS TotalClaims,
           SUM(CASE WHEN Status IN ('Submitted', 'UnderReview', 'NeedsMoreInfo') THEN 1 ELSE 0 END) AS OpenClaims
    FROM claims.Claims
    WHERE UserId IN (SELECT CAST(value AS INT) FROM OPENJSON(@UserIds))
    GROUP BY UserId;
END
GO
